"""Local, explainable relevance search over a user's summaries.

Ranking runs in Python after the caller's summaries have been selected through
an owner-scoped ORM query. The corpus is personal-scale and SQLite-backed, so
this keeps the feature dependency-free and avoids schema changes.

The search is deliberately lexical: it normalizes accents and case, removes
common function words, and expands a small bilingual concept lexicon (see
``apps.summaries.concepts``). Direct matches always score above matches found
only through a concept expansion, because a synonym is evidence of a nearby
idea, not proof that two memories mean the same thing.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass
from datetime import datetime
from typing import Any, Iterable

from .concepts import CONCEPTS, CONCEPTS_BY_KEY
from .models import Summary

MAX_QUERY_LENGTH = 200
MAX_QUERY_TERMS = 24
MAX_CONCEPTS_PER_QUERY = 8
MAX_MATCHED_TERMS = 12
SNIPPET_RADIUS = 90

# A prefix shorter than this is too likely to match unrelated words.
MIN_TERM_PREFIX = 4

# Direct matches: the query term itself, or one of its regular forms.
THEME_EXACT_SCORE = 6.0
THEME_TOKEN_SCORE = 3.5
SUMMARY_DIRECT_SCORE = 3.0
MOOD_EXACT_SCORE = 3.0
MOOD_TOKEN_SCORE = 2.5

# Expansion-only matches: the document expresses a nearby concept. They stay
# below the direct scores for the same field on purpose.
THEME_CONCEPT_SCORE = 3.0
SUMMARY_CONCEPT_SCORE = 1.2
MOOD_CONCEPT_EXACT_SCORE = 2.0
MOOD_CONCEPT_TOKEN_SCORE = 1.5

PHRASE_BONUS = 3.0
COVERAGE_SCORE = 2.0
MIN_SCORE = 1.0

FIELD_ORDER = ("themes", "summary_text", "mood")

# Normalized function words. Both languages are included because summaries
# generated by Gemini are usually English while users may query in French.
STOPWORDS = frozenset(
    """
    le la les un une des du de d au aux et ou a en dans sur sous par pour avec
    sans chez vers entre comme que qui quoi dont quand si ne pas plus moins tres
    trop bien tout tous toute toutes ce cet cette ces mon ma mes ton ta tes son
    sa ses notre nos votre vos leur leurs je tu il elle on nous vous ils elles
    me te se moi toi lui y est sont etait etaient ete suis es sommes etes ai as
    avons avez ont avoir etre fait faire fais sentais sentait senti sentir
    ressentais ressenti pensais pense souvenir souviens
    the a an and or of to in on at for with without from by about as is are was
    were be been being am do does did have has had i me my mine we our you your
    he she it they them their this that these those when where who whom which
    what how why if then than so but not no yes very too also just all any some
    more most much many can could should would will shall may might must felt
    feel feeling thought think remember
    """.split()
)

# Generic words that rarely discriminate between memories. Removing them
# prevents "moments" or "souvenirs" from matching almost everything.
GENERIC_WORDS = frozenset(
    """
    moment moments periode periodes epoque epoques souvenir souvenirs chose
    choses fois temps memorial memory memories thing things time times period
    periods
    """.split()
)

_PUNCTUATION_RE = re.compile(r"[^0-9a-z]+")
_LIGATURES = str.maketrans({"œ": "oe", "Œ": "oe", "æ": "ae", "Æ": "ae"})


class EmptySearchQuery(ValueError):
    """The query contains no useful term after normalization."""


@dataclass(frozen=True)
class QueryTerm:
    """One useful query term and the forms it can match.

    ``variants`` includes the direct form so callers can inspect the full
    expansion. ``concepts`` lists the concept keys that contributed expansions.
    """

    text: str
    variants: frozenset[str]
    concepts: frozenset[str] = frozenset()


@dataclass(frozen=True)
class SearchHit:
    """A scored summary and the evidence used to rank it."""

    summary: Any
    score: float
    matched_fields: list[str]
    matched_terms: list[str]
    snippet: str


def normalize_text(value: str) -> str:
    """Lowercase, strip accents, and reduce punctuation to spaces."""

    if not isinstance(value, str):
        return ""
    value = value.translate(_LIGATURES)
    value = unicodedata.normalize("NFKD", value)
    value = "".join(char for char in value if not unicodedata.combining(char))
    value = value.casefold()
    value = _PUNCTUATION_RE.sub(" ", value)
    return " ".join(value.split())


def _common_prefix_length(left: str, right: str) -> int:
    limit = min(len(left), len(right))
    index = 0
    while index < limit and left[index] == right[index]:
        index += 1
    return index


def _terms_match(left: str, right: str) -> bool:
    """Match a term to a document term without a stemming dependency.

    Exact matches, plural forms, long shared prefixes, and a shorter term that
    prefixes a longer one (when long enough) are accepted. The length guard
    avoids false positives such as ``exam``/``example``.
    """

    if not left or not right:
        return False
    if left == right:
        return True

    shorter, longer = (left, right) if len(left) <= len(right) else (right, left)
    if longer in (shorter + "s", shorter + "x"):
        return True
    if len(shorter) >= 5 and longer.startswith(shorter):
        return True
    return _common_prefix_length(left, right) >= 5


_CONCEPT_TERMS: dict[str, frozenset[str]] = {
    concept.key: frozenset(
        normalized
        for normalized in (normalize_text(term) for term in concept.terms)
        if normalized
    )
    for concept in CONCEPTS
}

_CONCEPT_TERM_LOOKUP: tuple[tuple[str, str], ...] = tuple(
    (term, concept_key)
    for concept_key, terms in _CONCEPT_TERMS.items()
    for term in sorted(terms)
)


def _concepts_for_term(token: str) -> tuple[str, ...]:
    """Return the concept keys whose forms match a normalized token."""

    keys: list[str] = []
    for concept_term, concept_key in _CONCEPT_TERM_LOOKUP:
        if concept_key in keys:
            continue
        if _terms_match(token, concept_term):
            keys.append(concept_key)
    return tuple(keys)


def build_query_terms(
    query: str,
    max_concepts: int = MAX_CONCEPTS_PER_QUERY,
) -> tuple[QueryTerm, ...]:
    """Normalize a query and expand each useful term through the lexicon.

    At most ``max_concepts`` distinct concepts are added to the whole query, so
    a long query cannot turn into an unbounded synonym list. Related concepts
    are followed one level only.
    """

    normalized = normalize_text(query)
    useful: list[str] = []
    for token in normalized.split():
        if len(token) < 2:
            continue
        if token in STOPWORDS or token in GENERIC_WORDS:
            continue
        if token not in useful:
            useful.append(token)

    useful = useful[:MAX_QUERY_TERMS]
    if not useful:
        raise EmptySearchQuery("Search query has no meaningful terms.")

    used_concepts: set[str] = set()
    terms: list[QueryTerm] = []

    for token in useful:
        variants = {token}
        concept_keys: list[str] = []
        seen_for_term: set[str] = set()

        candidates: list[str] = []
        for concept_key in _concepts_for_term(token):
            candidates.append(concept_key)
            candidates.extend(CONCEPTS_BY_KEY[concept_key].related)

        for concept_key in candidates:
            if concept_key in seen_for_term:
                continue
            seen_for_term.add(concept_key)
            if concept_key not in used_concepts:
                if len(used_concepts) >= max_concepts:
                    continue
                used_concepts.add(concept_key)
            concept_keys.append(concept_key)
            variants.update(_CONCEPT_TERMS[concept_key])

        terms.append(
            QueryTerm(
                text=token,
                variants=frozenset(variants),
                concepts=frozenset(concept_keys),
            )
        )

    return tuple(terms)


def _theme_forms(themes: Iterable[Any]) -> list[tuple[str, frozenset[str]]]:
    forms: list[tuple[str, frozenset[str]]] = []
    for theme in themes:
        if not isinstance(theme, str):
            continue
        phrase = normalize_text(theme)
        if phrase:
            forms.append((phrase, frozenset(phrase.split())))
    return forms


def _matched_tokens(
    tokens: Iterable[str], variants: frozenset[str]
) -> set[str]:
    return {
        token
        for token in tokens
        if any(_terms_match(variant, token) for variant in variants)
    }


def _contains_phrase(normalized_text: str, phrase: str) -> bool:
    return bool(phrase) and f" {phrase} " in f" {normalized_text} "


def _normalize_for_offsets(value: str) -> str:
    """Normalize while keeping one character per original character.

    This lets snippets point back into the original text even when accents
    are removed. It is only used for locating a match, not for scoring.
    """

    characters: list[str] = []
    for character in value:
        decomposed = unicodedata.normalize("NFKD", character)
        base = "".join(
            part for part in decomposed if not unicodedata.combining(part)
        ).casefold()
        if not base:
            characters.append(" ")
        elif base[0].isalnum():
            characters.append(base[0])
        else:
            characters.append(" ")
    return "".join(characters)


def build_snippet(
    text: str,
    matched_terms: Iterable[str],
    radius: int = SNIPPET_RADIUS,
) -> str:
    """Return a plain-text window around the first matched term."""

    if not isinstance(text, str) or not text.strip():
        return ""

    normalized = _normalize_for_offsets(text)
    positions = []
    for term in matched_terms:
        if not term:
            continue
        index = normalized.find(term)
        if index >= 0:
            positions.append(index)

    anchor = min(positions) if positions else 0
    start = max(0, anchor - radius)
    end = min(len(text), anchor + radius)
    snippet = text[start:end].strip()
    if start > 0:
        snippet = "…" + snippet
    if end < len(text):
        snippet = snippet + "…"
    return snippet


def _is_phrase_match(
    term_text: str,
    phrase: str,
    phrase_tokens: frozenset[str],
) -> bool:
    """True when the query term covers the whole single-word phrase."""

    if phrase == term_text:
        return True
    return len(phrase_tokens) == 1 and _terms_match(term_text, phrase)


def _theme_score(
    term: QueryTerm,
    theme_forms: list[tuple[str, frozenset[str]]],
    expanded_variants: frozenset[str],
) -> tuple[float, set[str]]:
    best_score = 0.0
    best_terms: set[str] = set()

    for phrase, theme_tokens in theme_forms:
        phrase_score = 0.0
        phrase_terms: set[str] = set()

        if _is_phrase_match(term.text, phrase, theme_tokens):
            phrase_score = THEME_EXACT_SCORE
            phrase_terms = {phrase}
        else:
            direct_terms = _matched_tokens(
                theme_tokens, frozenset({term.text})
            )
            if direct_terms:
                phrase_score = THEME_TOKEN_SCORE
                phrase_terms = direct_terms
            elif expanded_variants:
                expanded_terms = _matched_tokens(
                    theme_tokens, expanded_variants
                )
                if expanded_terms:
                    phrase_score = THEME_CONCEPT_SCORE
                    phrase_terms = expanded_terms

        if phrase_score > best_score:
            best_score = phrase_score
            best_terms = set(phrase_terms)
        elif phrase_score and phrase_score == best_score:
            best_terms.update(phrase_terms)

    return best_score, best_terms


def score_summary(
    summary: Any,
    terms: tuple[QueryTerm, ...],
) -> SearchHit | None:
    """Score one summary against pre-built query terms."""

    summary_text = getattr(summary, "summary_text", "") or ""
    mood = getattr(summary, "mood", "") or ""
    themes = getattr(summary, "themes", None) or []
    if not isinstance(summary_text, str):
        summary_text = ""
    if not isinstance(mood, str):
        mood = ""
    if not isinstance(themes, list):
        themes = []

    summary_normalized = normalize_text(summary_text)
    summary_tokens = frozenset(summary_normalized.split())
    theme_forms = _theme_forms(themes)
    mood_phrase = normalize_text(mood)
    mood_tokens = frozenset(mood_phrase.split())

    score = 0.0
    matched_fields: set[str] = set()
    matched_terms: list[str] = []
    matched_term_count = 0

    def remember(terms_to_add: Iterable[str]) -> None:
        for candidate in terms_to_add:
            if candidate and candidate not in matched_terms:
                matched_terms.append(candidate)

    for term in terms:
        term_score = 0.0
        term_fields: set[str] = set()
        term_terms: set[str] = set()
        expanded_variants = term.variants - {term.text}

        theme_hit_score, theme_hits = _theme_score(
            term, theme_forms, expanded_variants
        )
        if theme_hit_score:
            term_score += theme_hit_score
            term_fields.add("themes")
            term_terms.update(theme_hits)

        direct_summary_terms = _matched_tokens(
            summary_tokens, frozenset({term.text})
        )
        if direct_summary_terms:
            term_score += SUMMARY_DIRECT_SCORE
            term_fields.add("summary_text")
            term_terms.update(direct_summary_terms)
        elif expanded_variants:
            concept_summary_terms = _matched_tokens(
                summary_tokens, expanded_variants
            )
            if concept_summary_terms:
                term_score += SUMMARY_CONCEPT_SCORE
                term_fields.add("summary_text")
                term_terms.update(concept_summary_terms)

        if mood_phrase:
            if _is_phrase_match(term.text, mood_phrase, mood_tokens):
                term_score += MOOD_EXACT_SCORE
                term_fields.add("mood")
                term_terms.add(mood_phrase)
            else:
                direct_mood_terms = _matched_tokens(
                    mood_tokens, frozenset({term.text})
                )
                if direct_mood_terms:
                    term_score += MOOD_TOKEN_SCORE
                    term_fields.add("mood")
                    term_terms.update(direct_mood_terms)
                elif expanded_variants:
                    concept_mood_terms = _matched_tokens(
                        mood_tokens, expanded_variants
                    )
                    if concept_mood_terms:
                        term_score += (
                            MOOD_CONCEPT_EXACT_SCORE
                            if mood_phrase in expanded_variants
                            else MOOD_CONCEPT_TOKEN_SCORE
                        )
                        term_fields.add("mood")
                        term_terms.update(concept_mood_terms)

        if term_score > 0:
            score += term_score
            matched_term_count += 1
            matched_fields.update(term_fields)
            remember(term_terms)

    if matched_term_count == 0:
        return None

    if len(terms) > 1:
        query_phrase = " ".join(term.text for term in terms)
        if _contains_phrase(summary_normalized, query_phrase):
            score += PHRASE_BONUS
            matched_fields.add("summary_text")

        if matched_term_count == len(terms):
            score += COVERAGE_SCORE
        elif matched_term_count > 1:
            score += COVERAGE_SCORE / 2

    if score < MIN_SCORE:
        return None

    ordered_fields = [field for field in FIELD_ORDER if field in matched_fields]
    return SearchHit(
        summary=summary,
        score=round(score, 3),
        matched_fields=ordered_fields,
        matched_terms=matched_terms[:MAX_MATCHED_TERMS],
        snippet=build_snippet(summary_text, matched_terms),
    )


def _sort_key(hit: SearchHit) -> tuple[float, float, int]:
    summary = hit.summary
    created_at = getattr(summary, "created_at", None)
    timestamp = (
        created_at.timestamp()
        if isinstance(created_at, datetime)
        else 0.0
    )
    identifier = getattr(summary, "pk", None) or getattr(summary, "id", 0) or 0
    return (hit.score, timestamp, identifier)


def rank_summaries(
    summaries: Iterable[Any],
    query: str,
) -> list[SearchHit]:
    """Rank an already owner-scoped iterable of summaries."""

    terms = build_query_terms(query)
    hits: list[SearchHit] = []
    for summary in summaries:
        hit = score_summary(summary, terms)
        if hit is not None:
            hits.append(hit)
    hits.sort(key=_sort_key, reverse=True)
    return hits


def search_user_summaries(user: Any, query: str) -> list[SearchHit]:
    """Search only the authenticated user's summaries.

    The owner filter is applied in the ORM query before any ranking. No
    client-supplied user identifier is accepted.
    """

    summaries = Summary.objects.filter(owner=user).select_related("owner")
    return rank_summaries(summaries, query)
